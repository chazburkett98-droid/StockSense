import assert from 'node:assert/strict';
import {sampleInventory,validateItem,summarize,stockStatus,filterInventory,parseInventoryCSV,toInventoryCSV} from '../inventory-data.mjs';
const records=parseInventoryCSV('sku,name,category,quantity,unit,unitCost,reorderPoint,location\r\n001,"Sandwich, turkey",Fresh food,8,units,3.20,10,Front cooler\r\n002,Water,Drinks,20,cases,12,6,Aisle 1\r\n003,Juice,Drinks,0,units,1.80,10,Cooler');
assert.equal(records[0].sku,'001');
assert.equal(records[0].name,'Sandwich, turkey');
assert.deepEqual(summarize(records),{products:3,value:265.6,low:1,out:1,categories:2});
assert.equal(stockStatus(records[0]),'Low stock');
assert.equal(stockStatus(records[1]),'In stock');
assert.equal(stockStatus(records[2]),'Out of stock');
assert.equal(filterInventory(records,{search:'FRONT cooler'}).length,1);
assert.equal(filterInventory(records,{search:'001'})[0].sku,'001');
assert.equal(filterInventory(records,{category:'Drinks',status:'In stock'})[0].name,'Water');
assert.equal(filterInventory(records,{sort:'quantity'})[0].name,'Juice');
assert.equal(filterInventory(records,{sort:'value'})[0].name,'Water');
assert.equal(filterInventory(records,{search:'no such item'}).length,0);
assert.throws(()=>parseInventoryCSV('sku,name,quantity\n1,Water,-3'),/zero or greater/);
assert.throws(()=>parseInventoryCSV('sku,name,quantity\n1,Water,2\n1,Juice,5'),/unique SKU/);
assert.throws(()=>parseInventoryCSV('name,quantity\nWater,2'),/Missing CSV column: sku/);
assert.throws(()=>parseInventoryCSV('sku,name,quantity\n1,Water,2.5'),/whole numbers/);
assert.throws(()=>parseInventoryCSV('sku,name,quantity\n1,"Water,2'),/not closed/);
assert.throws(()=>parseInventoryCSV('sku,name,quantity\n1,Water,2,extra'),/wrong number/);
assert.equal(parseInventoryCSV('sku,name,quantity\n1,"Milk ""fresh""",2')[0].name,'Milk "fresh"');
assert.deepEqual(parseInventoryCSV(toInventoryCSV(records)),records);
assert.match(toInventoryCSV([{...records[0],name:'=SUM(1,2)'}]),/"'=SUM/);
assert.equal(validateItem({sku:'4',name:'Bread',quantity:0}).unit,'units');
assert.equal(sampleInventory.length,18);
assert.deepEqual(summarize([]),{products:0,value:0,low:0,out:0,categories:0});
console.log('Passed: inventory totals, filters, stock levels, CSV import/export, duplicate SKUs and invalid counts.');
